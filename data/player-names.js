/**
 * data/player-names.js
 * All static name pools used by Baseball GM.
 * ES module — no logic, no state references. Pure data.
 *
 * §82 LAST NAMES ONLY. The game never gives anyone a first name: players,
 * coaches and the people cards mention are known by their last name, the way
 * a broadcast or a box score calls them. A player whose last name is already
 * taken in the league gets a first initial ("E. Torres") — engine/Names.js.
 * Nothing in the game implies who the players are; anyone can picture their
 * own team.
 *
 * Name guidelines:
 *   - ASCII only — no diacritics or special characters
 *   - Weighted toward: American (white and African American), Hispanic
 *     (Latin America, Cuba, Dominican Republic, Venezuela), some Asian
 *     (Japanese, Korean, Taiwanese), some Italian- and Polish-American.
 *     No Scandinavian or West African names.
 *   - Every entry distinct, and none that reads as an ordinary word in a
 *     sentence ("Price wants the ball") — the name stands alone in the text.
 *   - The three pools never share a name: a coach is never mistaken for a player.
 *   - No surname of a well-known real player unless it's a common name (Garcia,
 *     Smith, Kim, Tanaka): "Puig" or "Altuve" points at one person. Checked by
 *     tools/harness/check-names.mjs, which lists the ones taken out.
 */

